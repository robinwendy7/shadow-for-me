SUFFIXES=['']
def quote(s):return json.dumps(s,ensure_ascii=False)
def generate():
 DATA.mkdir(parents=True,exist_ok=True)
 pools={k:[line+suffix for line in seeds.split('|') for suffix in SUFFIXES] for k,seeds in SEEDS.items()}
 text='-- 由 tools/build_data.py 生成：主题原句；不再附加通用陪伴句尾。\nreturn {\n'
 for k,lines in pools.items():text+='  '+k+'={\n'+''.join('    '+quote(s)+',\n' for s in lines)+'  },\n'
 (DATA/'dialogue.lua').write_text(text+'}\n',encoding='utf-8')
 for shard in range(64):
  values=[]
  for i in range(shard*8192,(shard+1)*8192):
   n=i; digits=[]
   for radix in reversed([4,4,8,4,4,4,4,4,4]):digits.append(n%radix);n//=radix
   phase,season,biome,sanity,hunger,danger,weather,memory,company=reversed(digits)
   # 评分实际用于队列排序：危险、低san、低饱食优先；有同伴时降低紧张。
   score=max(0,phase*4+season*2+biome+(3-sanity)*6+(3-hunger)*4+danger*12+weather*3+memory*2-company*2)
   values.append(str(score))
  content='-- 上下文评分分片 %02d；8192 个有效参数。\nreturn {\n'%shard
  content+='\n'.join(','.join(values[j:j+128])+',' for j in range(0,8192,128))+'\n}\n'
  (DATA/('context_%02d.lua'%shard)).write_text(content,encoding='utf-8')
 manifest={'context_parameters':524288,'context_shards':64,'dialogue_categories':len(pools),'dialogue_expressions':sum(map(len,pools.values())),'authored_seed_lines':len(pools)*5,'variants_per_seed':1,'dimensions':['phase:4','season:4','tile_mod8:8','sanity:4','hunger:4','danger:4','weather:4','daily_memory:4','other_players:4']}
 (ROOT/'data_manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
 print(json.dumps(manifest,ensure_ascii=False))
if __name__=='__main__':generate()
